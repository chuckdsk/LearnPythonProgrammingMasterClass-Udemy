# Basic Python print statements - the fundamental way to output information to the console

# Print a simple string greeting using single quotes
print('Hello, World!')

# Print the result of an arithmetic expression (addition)
print(1 + 2)

# Print the result of another arithmetic expression (multiplication)
print(7 * 6)

# Print an empty line (just a newline character) to create spacing
print()

# Print multiple arguments separated by spaces (comma-separated values)
# This demonstrates that print() can take multiple arguments and automatically adds spaces between them
print("The end","or is it?", "keep watching to learn more about Python", 3)
